function Particle({ shape, color, size, x, y, opacity, scale, rotate, delay, duration, repeat, repeatDelay }) {
  const d = PARTICLE_PATHS[shape] || PARTICLE_PATHS.star;
  const half = size / 2;
  // Soft glow so small particles read against dark text. Matches the editor preview.
  const glowR = Math.max(1, size * 0.4).toFixed(1);
  return (
    <motion.svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      style={{
        position: "absolute",
        left: -half,
        top: -half,
        pointerEvents: "none",
        transformOrigin: "center",
        filter: "drop-shadow(0 0 " + glowR + "px " + color + ")",
      }}
      initial={{ x: x[0], y: y[0], opacity: 0, scale: 0, rotate: rotate[0] }}
      animate={{ x, y, opacity, scale, rotate }}
      transition={Object.assign(
        { delay, duration, ease: "linear" },
        repeat ? { repeat: Infinity, repeatDelay } : {},
      )}
    >
      <path d={d} fill={color} />
    </motion.svg>
  );
}

